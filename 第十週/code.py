"""Code 模組：把 mnemonic 轉換成 Hack 二進位碼（課本 Table 6.2、6.3）。"""

DEST = {"": "000", "M": "001", "D": "010", "MD": "011",
        "A": "100", "AM": "101", "AD": "110", "AMD": "111"}

JUMP = {"": "000", "JGT": "001", "JEQ": "010", "JGE": "011",
        "JLT": "100", "JNE": "101", "JLE": "110", "JMP": "111"}

COMP = {
    # comp 位於 a=0（只用到 A 暫存器）
    "0":   "101010", "1":   "111111", "-1":  "111010",
    "D":   "001100", "A":   "110000", "!D":  "001101",
    "!A":  "110001", "-D":  "001111", "-A":  "110011",
    "D+1": "011111", "A+1": "110111", "D-1": "001110",
    "A-1": "110010", "D+A": "000010", "D-A": "010011",
    "A-D": "000111", "D&A": "000000", "D|A": "010101",
    # comp 位於 a=1（用 M，即 RAM[A]）
    "M":   "110000", "!M":  "110001", "-M":  "110011",
    "M+1": "110111", "M-1": "110010", "D+M": "000010",
    "D-M": "010011", "M-D": "000111", "D&M": "000000",
    "D|M": "010101",
}


def dest(dest_mnemonic: str) -> str:
    return DEST[dest_mnemonic]


def comp(comp_mnemonic: str) -> str:
    return COMP[comp_mnemonic]


def jump(jump_mnemonic: str) -> str:
    return JUMP[jump_mnemonic]
